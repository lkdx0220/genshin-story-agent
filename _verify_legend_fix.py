# 分组所有传说任务
series_groups = OrderedDict()
for q in 任务知识库:
    if q.get('任务类型') != '传说任务':
        continue
    s = q.get('系列任务', '')
    if not s:
        continue
    if s not in series_groups:
        series_groups[s] = []
    series_groups[s].append(q.get('任务名称', ''))

print("===== 验证结果 =====")
fixed_ok = 0
fixed_wrong = 0
need_recheck = []

for series_name, wiki_order in WIKI_ORDER.items():
    if series_name not in series_groups:
        print(f"  [未找到] {series_name}")
        continue
    
    db_order = series_groups[series_name]
    
    if sorted(wiki_order) == sorted(db_order):
        # 任务名集合匹配，检查顺序
        if wiki_order == db_order:
            fixed_ok += 1
        else:
            fixed_wrong += 1
            print(f"  [顺序错误] {series_name}")
            print(f"    Wiki: {wiki_order}")
            print(f"    DB:   {db_order}")
    else:
        # 任务名不匹配
        need_recheck.append((series_name, wiki_order, db_order))

print(f"\n正确: {fixed_ok}, 仍有错误: {fixed_wrong}")

if need_recheck:
    print(f"\n===== 需要重新核对的系列 ({len(need_recheck)} 个) =====")
    print("(wiki TOC 章节名与 DB 条目名不同，需逐页确认映射)")
    for s, wiki, db in need_recheck:
        print(f"\n  {s}")
        print(f"    Wiki: {' -> '.join(wiki)}")
        print(f"    DB:   {' -> '.join(db)}")
