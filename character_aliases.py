def resolve_aliases(query: str) -> list:
    """根据别名查规范名列表（供工具内部使用）"""
    query_clean = query.strip().replace("「", "").replace("」", "")
    return CHARACTER_ALIASES.get(query_clean, [query_clean])


def build_alias_map() -> Dict[str, str]:
    """从 CHARACTER_ALIASES 构建 别名→规范名 的确定性映射。
    如果一个别名对应多个不同规范名（如"火神"→玛薇卡/班尼特），跳过该别名，交给 LLM 自行消歧。
    单字别名（如"影"）也跳过，中文单字在复合词中误伤率太高。"""
    alias_map: Dict[str, str] = {}
    alias_conflicts: Dict[str, set] = {}
    skipped_single_char: list = []
    for canonical, aliases in CHARACTER_ALIASES.items():
        for alias in aliases:
            clean = alias.strip().replace("「", "").replace("」", "")
            if len(clean) == 1:
                skipped_single_char.append(f"{clean}→{canonical}")
                continue
            if clean in alias_map and alias_map[clean] != canonical:
                # 同一别名指向不同角色 → 冲突
                if clean not in alias_conflicts:
                    alias_conflicts[clean] = {alias_map[clean]}
                alias_conflicts[clean].add(canonical)
            else:
                alias_map[clean] = canonical
    for conflict_alias in alias_conflicts:
        if conflict_alias in alias_map:
            del alias_map[conflict_alias]
    if alias_conflicts:
        conflict_summary = ", ".join(
            f"{k}→{'/'.join(sorted(v))}" for k, v in sorted(alias_conflicts.items())
        )
        print(f"[别名映射] 跳过 {len(alias_conflicts)} 个歧义别名，交给 LLM 消歧: {conflict_summary}")
    if skipped_single_char:
        print(f"[别名映射] 跳过 {len(skipped_single_char)} 个单字别名（易误伤复合词），交给 LLM 消歧: {', '.join(skipped_single_char)}")
    return alias_map


# 模块加载时预计算映射表和排序列表
ALIAS_MAP = build_alias_map()
ALIASES_SORTED = sorted(ALIAS_MAP.keys(), key=len, reverse=True)
